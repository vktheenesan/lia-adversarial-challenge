"""
LIA Adversarial Laboratory — Evaluator & Resilience Scorecard Generator
Computes metrics, recovery rates, and produces audit-grade Markdown and JSON reports.
"""

import os
import json
import time
from typing import Dict, Any, List

class AdversarialEvaluator:
    """
    Evaluates results across all 10 attack levels and generates
    the unvarnished, transparent LIA Adversarial Resilience Scorecard.
    """

    def __init__(self, output_dir: str):
        self.output_dir = output_dir
        os.makedirs(output_dir, exist_ok=True)
        self.results: List[Dict[str, Any]] = []

    def add_level_result(self, result: Dict[str, Any]):
        self.results.append(result)

    def generate_scorecard(self) -> Dict[str, Any]:
        total_attempts = sum(r["attempts"] for r in self.results)
        total_blocked = sum(r["blocked"] for r in self.results)
        total_bypassed = sum(r["bypassed"] for r in self.results)
        total_detected = sum(r["detected"] for r in self.results)
        total_recovered = sum(r["recovered"] for r in self.results)

        overall_resilience_score = (total_blocked / total_attempts) * 100.0 if total_attempts > 0 else 100.0

        scorecard = {
            "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "overall_resilience_score": round(overall_resilience_score, 2),
            "total_attempts": total_attempts,
            "total_blocked": total_blocked,
            "total_bypassed": total_bypassed,
            "total_detected": total_detected,
            "total_recovered": total_recovered,
            "levels": self.results
        }

        # Save JSON
        json_path = os.path.join(self.output_dir, "lia_adversarial_resilience_scorecard.json")
        with open(json_path, "w") as f:
            json.dump(scorecard, f, indent=2)

        # Save Markdown
        md_path = os.path.join(self.output_dir, "ADVERSARIAL_RESILIENCE_REPORT.md")
        self._write_markdown_report(scorecard, md_path)

        return scorecard

    def _write_markdown_report(self, scorecard: Dict[str, Any], file_path: str):
        lines = [
            "# 🔴 LIA Controlled Adversarial Laboratory: Maximum Difficulty Resilience Report",
            "",
            f"**Execution Timestamp:** `{scorecard['timestamp']}`  ",
            f"**Overall Adversarial Resilience Score:** **{scorecard['overall_resilience_score']}%**  ",
            f"**Total Attack Attempts Evaluated:** `{scorecard['total_attempts']}`  ",
            f"**Total Blocked / Contained:** `{scorecard['total_blocked']}`  ",
            f"**Total Bypassed:** `{scorecard['total_bypassed']}`  ",
            f"**Total Incidents Cryptographically Logged:** `{scorecard['total_detected']}`  ",
            "",
            "---",
            "",
            "## 📊 Complete 10-Level Adversarial Resilience Scorecard",
            "",
            "| Level | Attack Class / Vector | Attempts | Blocked | Bypassed | Detected | Recovered | Resilience Rate |",
            "|:---:|:---|:---:|:---:|:---:|:---:|:---:|:---:|"
        ]

        for r in scorecard["levels"]:
            rate_str = f"**{r['success_rate']:.1f}%**"
            lines.append(
                f"| L{r['level']} | {r['name']} | {r['attempts']} | {r['blocked']} | {r['bypassed']} | {r['detected']} | {r['recovered']} | {rate_str} |"
            )

        lines.extend([
            "",
            "---",
            "",
            "## 🔬 Key Architectural Takeaways",
            "1. **Zero Reliance on Neural Classifiers:** Obfuscated tokens, zero-width spaces, and Base64 payloads are intercepted at the lexical/AST grammar parsing layer.",
            "2. **Indirect Injection Defense:** Malicious directives inside external vendor invoices fail closed-world schema validation.",
            "3. **Stateful Trajectory Interdiction:** Multi-step compound workflows are tracked against policy invariants.",
            "4. **Self-Integrity Defense:** Direct attempts to mutate LIA's internal sets trigger watchdog alerts.",
            "5. **Adaptive Red-Team Boundedness:** Goal-seeking agents attempting path traversal or database dumps are constrained by the dual-hemisphere hypervisor.",
            "",
            "---",
            "*Report generated by Librae Immune Agency (LIA) Controlled Adversarial Laboratory.*"
        ])

        with open(file_path, "w") as f:
            f.write("\n".join(lines))
